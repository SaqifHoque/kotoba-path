create table review_event (
    sequence_id bigint generated by default as identity primary key,
    profile_id varchar(36) not null references study_profile(id),
    event_id varchar(36) not null,
    kind varchar(12) not null,
    outcome varchar(12) not null,
    received_at bigint not null,
    event_json text not null,
    unique (profile_id, event_id)
);
create index review_event_profile_sequence on review_event(profile_id, sequence_id);
