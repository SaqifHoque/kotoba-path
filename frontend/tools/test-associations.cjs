const assert = require('node:assert/strict'), path = require('node:path');
const root = process.argv[2];
const {buildAssociationIndex} = require(path.join(root,'associations/association-index.js'));
const {associationSearch} = require(path.join(root,'associations/association-search.js'));
const {buildForge} = require(path.join(root,'forge/forge-engine.js'));
const {applyCurriculum} = require(path.join(root,'learn/curriculum-manifest.js'));
const {sectionFor} = require(path.join(root,'study/study-overview.js'));
const cards = applyCurriculum(require('../src/assets/kanji-curriculum.json'),require('../src/assets/curriculum-manifest.json'));
const subjects = buildForge(cards), before = JSON.stringify(subjects);
const index = buildAssociationIndex(subjects), search = associationSearch(subjects);
const ids = items => items.map(item=>item.id);
const rest = index.details('k:休');
assert.deepEqual(rest.components.map(link=>[link.subject.id,link.form]),[['k:人','亻'],['k:木','木']]);
assert.deepEqual(ids(rest.primaryRadicals),['r:⺅']);
assert(rest.words.some(word=>word.id==='v:休む:やすむ'));
assert(rest.words.some(word=>word.id==='v:休日:きゅうじつ'));
assert.deepEqual(new Set(ids(index.details('k:木').usedInKanji)),new Set(['k:休','k:林','k:森']));
assert.deepEqual(ids(index.details('k:日').usedInKanji),['k:明']);
assert.deepEqual(ids(index.details('v:休日:きゅうじつ').kanji),['k:休','k:日']);
const siblings = index.details('v:休日:きゅうじつ').words;
assert(siblings.some(word=>word.id==='v:休む:やすむ'));
assert(!siblings.some(word=>word.id==='v:休日:きゅうじつ'));
assert.equal(new Set(ids(siblings)).size,siblings.length);
assert(index.details('r:木').classifiedKanji.some(subject=>subject.id==='k:木'));
assert.equal(index.details('r:木').components.length,0);
assert.equal(index.details('r:木').usedInKanji.length,0,'dictionary classification must not invent teaching-component links');
assert.equal(index.details('k:一').components.length,0,'missing authored decomposition stays unknown');
assert.equal(index.details('missing'),null);
for(const subject of subjects){
 const detail=index.details(subject.id);assert.equal(detail.subject.id,subject.id);
 for(const word of detail.words){assert(word.kind==='vocabulary');assert(word.prerequisites.some(id=>subject.kind==='vocabulary'?subject.prerequisites.includes(id):id===subject.id))}
 if(subject.kind==='vocabulary')assert.deepEqual(new Set(ids(detail.kanji)),new Set(subject.prerequisites));
}
const first = index.details('k:休');first.words.length=0;first.components.length=0;
assert(index.details('k:休').words.length>0);assert.equal(index.details('k:休').components.length,2);
assert.equal(search('').items.length,11);
assert.equal(search('  ').total,11);
assert.equal(search('休').items[0].id,'k:休');
assert.equal(search('休日').items[0].id,'v:休日:きゅうじつ');
assert(search('やすむ').items.some(item=>item.id==='v:休む:やすむ'));
assert.deepEqual(ids(search('ﾔｽﾑ').items),ids(search('やすむ').items),'normalize full/half-width kana');
assert(search('WOOD').items.some(item=>item.id==='k:木'));
assert(search('day off').items.some(item=>item.id==='v:休日:きゅうじつ'),'curated meaning aliases are searchable');
assert.equal(search('no_such_item_zzz').total,0);
assert.deepEqual(search('tree'),search('tree'),'search ordering is deterministic');
const limited=associationSearch(subjects,2)('a');assert.equal(limited.items.length,2);assert(limited.total>2);
assert.throws(()=>associationSearch(subjects,0));assert.throws(()=>associationSearch(subjects,101));
assert.throws(()=>buildAssociationIndex([...subjects,subjects[0]]),/Duplicate/);
const badComponent={...subjects.find(item=>item.id==='k:休'),components:[{subjectId:'k:missing',form:'?'}]};
assert.throws(()=>buildAssociationIndex(subjects.map(item=>item.id===badComponent.id?badComponent:item)),/Missing component/);
const badWord={...subjects.find(item=>item.id==='v:休日:きゅうじつ'),prerequisites:['k:missing']};
assert.throws(()=>buildAssociationIndex(subjects.map(item=>item.id===badWord.id?badWord:item)),/Missing word kanji/);
assert.equal(JSON.stringify(subjects),before,'index construction and exploration preserve the shared catalog');
assert.equal(sectionFor('associations'),'library');
console.log('PASS: authored components versus dictionary classification; bidirectional kanji/word links; related-word deduplication; complete catalog coverage; normalized and bounded search; unknown IDs; invalid references; unchanged catalog.');
