const assert = require('node:assert/strict');
const engine = require(process.argv[2]);
const review = require(process.argv[3]);
const cards = require('../src/assets/kanji-curriculum.json');
const words = engine.buildVocabulary(cards);
assert(words.length > 2500);
assert.equal(new Set(words.map(w => w.id)).size, words.length);
const state = (due = 100) => ({learned:true,stage:1,due,attempts:1});
const river = words.find(w => w.text === '川');
assert(!engine.availableWords(words, {}).includes(river));
assert(engine.availableWords(words, {'川':state()}).includes(river));
const people = words.find(w => w.text === '三人');
assert(!engine.availableWords(words, {'三':state()}).includes(people));
assert(engine.availableWords(words, {'三':state(), '人':state()}).includes(people));
assert(engine.readingMatches(' サンニン ', 'さんにん'));
assert(engine.readingMatches('じゅうなな', 'じゅうしち/じゅうなな'));
assert(!engine.readingMatches('', 'さんにん'));
assert(!engine.readingMatches('さんじん', 'さんにん'));
const progress = Object.fromEntries(cards.map(c => [c.character, state()]));
const vocabulary = {[words[0].id]: state(999), [words[1].id]: state(50)};
const pending = engine.wordQueue(words, vocabulary, 100);
assert.equal(pending[0], words[1]);
assert(!pending.includes(words[0]));
const queue = engine.mixedQueue(cards, progress, words, vocabulary, 100);
assert.equal(queue.length, 20);
assert.equal(queue[0].kind, 'kanji');
assert.equal(queue[1].kind, 'reading');
assert.equal(queue[3].kind, 'meaning');
assert.equal(queue[1].word.id, words[1].id);
assert.deepEqual(review.parseProgress(JSON.stringify({version:1,cards:vocabulary}), words.map(w=>({character:w.id}))), vocabulary);
assert.throws(()=>review.parseProgress('{bad',words.map(w=>({character:w.id}))));
assert.equal(engine.mixedQueue(cards, {}, words, {}, 100).length, 0);
for (const word of words.filter(w=>w.context)) {
  assert(word.context[0].includes(word.text));
  assert([...word.context[0].matchAll(/\p{Script=Han}/gu)].every(m=>word.prerequisites.includes(m[0])));
}
assert(engine.availableWords(words, {}, ['三','人']).includes(people));
assert(!engine.availableWords(words, {'人':{...state(),learned:false}}, ['三','人']).includes(people));
console.log(`PASS: ${words.length} unique words; prerequisites, assumed knowledge, kana answers, due ordering, mixed sessions, persistence, contexts.`);
