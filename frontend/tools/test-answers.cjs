const assert = require('node:assert/strict');
const path = require('node:path');
const root = process.argv[2];
const a = require(path.join(root, 'learn/answer-checker.js'));
const s = require(path.join(root, 'learn/meaning-synonyms.js'));
const f = require(path.join(root, 'forge/forge-engine.js'));
const subject = {id:'k:大',kind:'kanji',meaning:'big',readings:['だい / たい'],otherReadings:['おお']};
const status = (skill, value, personal=[]) => a.checkAnswer(subject,skill,value,personal).status;
assert.equal(status('meaning','large'),'correct');
assert.equal(status('meaning','the big'),'correct');
assert.equal(status('meaning','bgi'),'incorrect');
assert.equal(status('meaning','big (small)'),'incorrect');
assert.equal(status('meaning','だい'),'retry');
assert.equal(status('meaning','huge',['huge']),'correct');
assert.equal(a.checkAnswer(subject,'meaning','huge',['huge']).origin,'personal');
assert.equal(status('reading','huge',['huge']),'retry');
assert.equal(status('reading','ダイ'),'correct');
assert.equal(status('reading','ﾀｲ'),'correct');
assert.equal(status('reading','おお'),'retry');
assert.equal(status('reading','dai'),'retry');
assert.equal(status('reading','大'),'retry');
assert.equal(status('reading','だ'),'incorrect');
assert.equal(status('reading',''),'incorrect');
assert.equal(a.checkReading('きよう',['きょう']).status,'incorrect');
assert.equal(a.checkReading('こ',['こう']).status,'incorrect');
assert.equal(a.checkReading('たべ',['たべる']).status,'incorrect');
assert.deepEqual(a.sourceMeanings('bright (light, clear); [adj.] clever / wise'),['bright','clever','wise']);
assert.deepEqual(a.sourceMeanings('be (alive), noun suffix'),['be (alive)']);
assert.equal(a.normalizeMeaning('a well–known person'),a.normalizeMeaning('well-known person'));
assert.equal(a.normalizeMeaning('one’s'),a.normalizeMeaning("one's"));
assert.deepEqual(s.cleanSynonyms([' Huge ', 'huge', 'vast']),['Huge','vast']);
for(const invalid of [['だい'],['[n.]'],[''],['x\nx'],['x'.repeat(81)],Array(9).fill('big')]) assert.throws(()=>s.cleanSynonyms(invalid));
const ids=new Set(['k:大']);
assert.deepEqual(s.parseMeaningSynonyms(undefined,ids),{});
assert.deepEqual(s.parseMeaningSynonyms({'k:小':{values:['little'],updatedAt:1}},ids),{});
for(const invalid of [null,[],{'k:大':{values:['huge'],updatedAt:-1}},{'k:大':{values:['大'],updatedAt:1}}])assert.throws(()=>s.parseMeaningSynonyms(invalid,ids));
const initial=s.setMeaningSynonyms({},subject.id,['huge'],100);
const removed=s.setMeaningSynonyms(initial,subject.id,[],99);
assert.equal(removed[subject.id].updatedAt,101);
assert.deepEqual(s.mergeMeaningSynonyms(removed,initial),removed);
assert.deepEqual(s.mergeMeaningSynonyms(initial,removed),removed);
assert.deepEqual(s.mergeMeaningSynonyms(initial,initial),initial);
assert.deepEqual(s.mergeMeaningSynonyms(initial,{'k:大':{values:[],updatedAt:100}})['k:大'].values,[]);
const other={'k:大':{values:['vast'],updatedAt:100}};
assert.deepEqual(s.mergeMeaningSynonyms(initial,other),s.mergeMeaningSynonyms(other,initial));
const before=f.emptyForge();
const next={...before,meaningSynonyms:initial};
const restored=f.parseForge(JSON.parse(JSON.stringify(next)),[subject]);
assert.deepEqual(restored.meaningSynonyms,initial);
assert.deepEqual(restored.records,before.records);
assert.deepEqual(f.mergeForge(next,{...before,meaningSynonyms:removed}).meaningSynonyms,removed);
assert.deepEqual(f.parseForge({...before,meaningSynonyms:undefined},[subject]).meaningSynonyms,{});
const catalog=JSON.parse(require('node:fs').readFileSync('src/assets/kanji-curriculum.json','utf8'));
const cards=Array.isArray(catalog)?catalog:catalog.cards;
assert.ok(cards, 'catalog cards exist');
for(const [id,aliases] of Object.entries(a.MEANING_ALIASES)){
  const card=cards.find(c=>c.character===id.slice(2)); assert.ok(card,id);
  for(const alias of aliases)assert.equal(a.checkAnswer({...subject,id,meaning:card.meaning},'meaning',alias).status,'correct');
}
console.log('Answer checking, retry boundaries, synonym validation and merge tests passed.');
