const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const engine = require(path.resolve(process.argv[2]));
const cards = JSON.parse(fs.readFileSync(path.join(__dirname, '../src/assets/kanji-curriculum.json'), 'utf8'));
const {buildLevels, schedule, DAY, dueCards, levelDone, unlocked, parseProgress} = engine;
const levels = buildLevels(cards);
const now = 1700000000000;
let progress = {};
assert(unlocked(levels, 0, progress));
assert(!unlocked(levels, 1, progress));
assert(!unlocked(levels, -1, progress));
for (const card of levels[0].cards.slice(0, -1)) progress[card.character] = schedule(undefined, 'good', now);
assert(!levelDone(levels[0], progress));
assert(!unlocked(levels, 1, progress));
const last = levels[0].cards.at(-1).character;
progress[last] = schedule(undefined, 'again', now);
assert(!levelDone(levels[0], progress));
progress[last] = schedule(progress[last], 'good', now);
assert(levelDone(levels[0], progress));
assert(unlocked(levels, 1, progress));
assert(!unlocked(levels, 2, progress));
assert.equal(dueCards(cards, progress, now + DAY - 1).length, 0);
assert.equal(dueCards(cards, progress, now + DAY).length, 12);
let state;
for (const days of [1, 3, 7, 14, 30, 60, 120, 120]) {
  state = schedule(state, 'good', now);
  assert.equal(state.due, now + days * DAY);
}
const lapse = schedule(state, 'again', now);
assert.equal(lapse.due, now + 600000);
assert.equal(lapse.stage, 0);
assert.equal(lapse.learned, true);
assert.equal(schedule(lapse, 'good', now).due, now + DAY);
assert.equal(schedule(state, 'hard', now).due, now + DAY);
const restored = parseProgress(JSON.stringify({version: 1, cards: progress}), cards);
assert.deepEqual(restored, progress);
assert.equal(dueCards(cards, restored, now + DAY).length, 12);
assert.throws(() => parseProgress('{bad json', cards));
assert.throws(() => parseProgress(JSON.stringify({version: 1, cards: {[last]: {...state, due: 'bad'}}}), cards));
assert.throws(() => parseProgress(JSON.stringify({version: 1, cards: {[last]: {...state, stage: 50}}}), cards));
assert.deepEqual(parseProgress(null, cards), {});
assert(!unlocked(levels, 0.5, progress));
assert(!unlocked(levels, levels.length, progress));
const early = cards[0].character, late = cards[1].character;
const mixed = {[early]: schedule(undefined, 'again', now), [late]: schedule(undefined, 'good', now)};
assert.equal(dueCards(cards, mixed, now + 599999).length, 0);
assert.deepEqual(dueCards(cards, mixed, now + 600000).map(c => c.character), [early]);
assert.deepEqual(dueCards([...cards].reverse(), mixed, now + DAY).map(c => c.character), [early, late]);
assert.equal(mixed[early].learned, false);
assert.equal(schedule(undefined, 'hard', now).learned, true);
assert.equal(schedule(undefined, 'hard', now).stage, 0);
assert.equal(schedule(state, 'hard', now).stage, state.stage - 1);
assert.equal(schedule(state, 'good', now).attempts, state.attempts + 1);
const previous = {...state};
schedule(state, 'again', now);
assert.deepEqual(state, previous);
for (const invalid of [null, [], {...state, due:-1}, {...state, attempts:0}, {...state, learned:'yes'}]) {
  assert.throws(() => parseProgress(JSON.stringify({version:1, cards:{[last]:invalid}}), cards));
}
assert.throws(() => parseProgress(JSON.stringify({version:2, cards:{}}), cards));
assert.throws(() => parseProgress(JSON.stringify({version:1, cards:[]}), cards));
assert.deepEqual(parseProgress(JSON.stringify({version:1, cards:{unknown:state}}), cards), {});
console.log('PASS: unlocking, review intervals and lapses, due ordering and boundaries, serialization, corrupt data.');
