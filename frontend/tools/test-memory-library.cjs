const assert=require('node:assert/strict'),path=require('node:path');
const root=process.argv[2],m=require(path.join(root,'memory/memory-library.js'));
const f=require(path.join(root,'forge/forge-engine.js'));
const subjects=f.buildForge(require('../src/assets/kanji-curriculum.json'));
const byId=new Map(subjects.map(s=>[s.id,s])),state=f.emptyForge();
const person='k:人',word='v:人:ひと',tree='k:木';
const record=(note,at)=>({meaning:{stage:5,due:12345,reviews:4,correct:4,misses:0,updatedAt:1000},
 reading:{stage:5,due:12345,reviews:4,correct:4,misses:0,updatedAt:1000},lessonAt:100,note,noteAt:at});
state.records[person]=record('Walking beside a tree',1000);
state.records[tree]=record('   ',9000);
state.meaningSynonyms[person]={values:['someone'],updatedAt:1200};
state.meaningSynonyms[word]={values:['individual'],updatedAt:2000};
state.meaningSynonyms[tree]={values:[],updatedAt:9999};
state.records['k:unknown']=record('Orphan must not appear',5000);
state.meaningSynonyms['v:unknown:かな']={values:['orphan'],updatedAt:5000};
const before=JSON.stringify(state),catalogBefore=JSON.stringify(subjects);
const saved=m.savedMemories([...subjects,byId.get(person)],state);
assert.equal(saved.length,2);assert.equal(saved.find(i=>i.id===word).introduced,false);
assert.equal(saved.find(i=>i.id===person).introduced,true);
const defaults={query:'',kind:'all',content:'all',sort:'recent'};
assert.deepEqual(m.memoryMatches(saved,defaults).map(i=>i.id),[word,person]);
const find=query=>m.memoryMatches(saved,{...defaults,query});
assert.deepEqual(find('ヒト').map(i=>i.id),[word]);
assert.deepEqual(find('ＳＯＭＥＯＮＥ').map(i=>i.id),[person]);
assert.deepEqual(find('walking tree').map(i=>i.id),[person]);
assert.deepEqual(find('someone walking').map(i=>i.id),[person]);
assert.deepEqual(find('does not exist'),[]);
assert.deepEqual(m.memoryMatches(saved,{...defaults,content:'notes'}).map(i=>i.id),[person]);
assert.equal(m.memoryMatches(saved,{...defaults,content:'synonyms'}).length,2);
assert.deepEqual(m.memoryMatches(saved,{...defaults,kind:'vocabulary'}).map(i=>i.id),[word]);
assert.equal(m.memoryMatches(saved,{...defaults,kind:'radical'}).length,0);
assert.deepEqual(m.memoryMatches(saved,{...defaults,sort:'text'}).map(i=>i.id),[person,word]);
assert.equal(JSON.stringify(state),before);assert.equal(JSON.stringify(subjects),catalogBefore);
saved[0].synonyms.push('local only');saved[0].readings.push('local only');
assert.equal(JSON.stringify(state),before);assert.equal(JSON.stringify(subjects),catalogBefore);
const cleared=structuredClone(state);cleared.records[person].note='';cleared.meaningSynonyms[person].values=[];
assert.deepEqual(m.savedMemories(subjects,cleared).map(i=>i.id),[word]);
console.log('PASS memory library: actual content only, known IDs, dedupe, introduced status, kana/NFKC/multifield search, kind/content filters, deterministic sorting, clearing and immutable source data.');
