const assert=require('node:assert/strict'),path=require('node:path');
const root=process.argv[2],p=require(path.join(root,'pacing/study-pacing.js'));
const f=require(path.join(root,'forge/forge-engine.js'));
const subjects=f.buildForge(require('../src/assets/kanji-curriculum.json'));
const now=new Date(2026,10,18,12).getTime(),day=86400000;
const kanji=subjects.filter(s=>s.kind==='kanji').slice(0,51);
const track=(due,stage=1)=>({stage,due,reviews:0,correct:0,misses:0,updatedAt:now-day});
const record=(due)=>({meaning:track(due),reading:track(due),lessonAt:now-day,note:'Keep',noteAt:now});
let state=f.emptyForge();
let result=p.studyPacing(subjects,state,now);
assert.equal(result.reason,'available');assert.equal(result.allowance,10);assert.equal(result.dueQuestions,0);
state.records[kanji[0].id]=record(now-7*day);
result=p.studyPacing(subjects,state,now);
assert.equal(result.heading,'Pick up gently');assert.equal(result.olderQuestions,2);assert.equal(result.dueSubjects,1);
state.records[kanji[0].id].reading.due=now-7*day+1;
assert.equal(p.studyPacing(subjects,state,now).olderQuestions,1);
state.records[kanji[0].id].meaning=track(null,9);
assert.equal(p.studyPacing(subjects,state,now).olderQuestions,0);
state.records[kanji[0].id].reading.due=now+1000;
result=p.studyPacing(subjects,state,now);
assert.equal(result.dueQuestions,0);assert.equal(result.nextReviewAt,now+1000);
state=f.emptyForge();
for(const s of kanji.slice(0,10))state.records[s.id]=record(now);
result=p.studyPacing(subjects,state,now);
assert.equal(result.dueQuestions,20);assert.equal(result.reason,'backlog');assert.equal(result.allowance,0);
state.records[kanji[0].id].reading.due=now+1000;
assert.equal(p.studyPacing(subjects,state,now).reason,'available');
assert.equal(p.studyPacing(subjects,state,now).dueQuestions,19);
for(const s of kanji.slice(0,50))state.records[s.id]=record(now+1000);
result=p.studyPacing(subjects,state,now);
assert.equal(result.apprentice,50);assert.equal(result.reason,'apprentice');assert.equal(result.allowance,0);
state=f.emptyForge();
for(const s of kanji.slice(0,5)){state.records[s.id]=record(now+1000);state.records[s.id].lessonAt=now;}
state.dailyLimit=5;
result=p.studyPacing(subjects,state,now);
assert.equal(result.introducedToday,5);assert.equal(result.reason,'daily-limit');assert.equal(result.allowance,0);
const before=structuredClone(state),updated=p.withDailyLimit(state,10,now);
assert.deepEqual(state,before);assert.equal(updated.records,state.records);assert.equal(updated.settingsAt,now);
assert.equal(updated.dailyLimit,10);assert.equal(updated.unlockedLevel,state.unlockedLevel);
assert.equal(p.studyPacing(subjects,updated,now).allowance,5);
assert.equal(p.withDailyLimit(updated,10,now+1),updated);
assert.throws(()=>p.withDailyLimit(updated,0,now));assert.throws(()=>p.withDailyLimit(updated,NaN,now));
const lower=p.withDailyLimit(state,5,now);
assert.deepEqual(lower,state);
for(const limit of [5,10,20])assert.equal(p.withDailyLimit(state,limit,now).dailyLimit,limit);
assert.equal(p.studyPacing(subjects,state,now).allowance,f.lessonAllowance(subjects,state,now));
console.log('PASS pacing: seven-day overdue boundary, independent/Burned tracks, due guards at 19/20, Apprentice guard at 50, local introductions, limit validation/idempotence and untouched records/levels.');
